//! Real USB keyboards' descriptors, for the fake controller (usb_fake.zig).
//! Captured 2026-10-04 on the user's desktop from sysfs, without root:
//!
//!   od -An -tx1 -v /sys/bus/usb/devices/<dev>/descriptors
//!       (the device descriptor, then the whole configuration as the
//!       kernel read it)
//!   od -An -tx1 -v /sys/bus/usb/devices/<dev>/<dev>:1.N/0003:*/report_descriptor
//!   cat /sys/bus/usb/devices/<dev>/{manufacturer,product,serial}
//!
//! Both are full-speed combo devices: a boot keyboard on interface 0 and a
//! mouse (with more report IDs) on interface 1. They differ where a host
//! can go wrong: endpoint 0 takes 64 bytes on one and 8 on the other, and
//! the second keyboard's report protocol sends 18-byte reports (16 key
//! slots) that only SET_PROTOCOL(boot) turns into the 8-byte boot format.

pub const Fixture = struct {
    name: []const u8,
    device: []const u8,
    config: []const u8,
    /// report descriptors, by interface number
    reports: []const []const u8,
    /// string descriptors' text, by index (index 0, the language list, is
    /// made by the fake); null = the device stalls the request
    strings: []const ?[]const u8,
    /// key slots of interface 0's report-protocol input report (boot
    /// protocol always has 6)
    report_keys: u8,
};

