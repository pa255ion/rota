{-|
The Super Nintendo demo's data (M7 step 7.13; @demos/snes/rota.s@,
WLA-DX): "Rota.Snes"'s pictures as the streams the ROM plays, the same
records "Rota.Sega.Rom" makes for the Sega machines (each the difference
between consecutive pictures, the idle loops with their own periods) in
the SNES's own formats.

__VRAM__ (word addresses): one 4bpp tile space from 0, the sprite
patterns first (OBSEL's name base 0, 8 × 8 sprites), then the background's
tiles (BG1's character base 0: blank, the fabric slots, a tile per logo
cell; 16 words a tile); BG1's tilemap at 7000h (32 × 32 entries, the 28
rows the screen shows), set once: a logo cell's entry has the priority
bit (2000h), so a sprite (priority 2) shows over its background pixels
and behind the logo's, as the lab draws sparks behind the logo.

__CGRAM:__ the background's colours at 0 to 15 (palette 0), the sprites'
nine at 129 to 137 (palette 0 of the sprites; 128 transparent), 15-bit
('cgram15').

__Each frame__ (the NMI at line 225, to line 0 of the next frame: 37 lines
of 1364 master clocks, 'snesBudget'), the ROM plays one record of each
stream: the sound (DSP writes through the SPC700's driver, "Rota.Sound.
Snes"), the colours (a CGRAM index and its colour; FFh, 0Fh: the display
on, at the first beat), the tiles (a VRAM word address and a library
graphic's 24-bit address: 32 bytes by DMA), the sparks' and the lights'
OAM entries (slot, X, Y, tile; BG1 unscrolled; hidden at Y E0h). A
record is a count and that many
operations; FEh and a 24-bit address jump to the stream's idle loop; FFh
ends the sound.
-}
module Rota.Snes.Rom
  ( snesRom
  , snesRomInc
  , snesSpcInc
  , snesExpected
  , snesFrameCosts
  , snesBudget
  , snesStats
  , cgOf
  , tileBytes4
  ) where

import Data.Bits (shiftL, testBit, (.|.))
import qualified Data.Map.Strict as M
import qualified Data.Vector.Unboxed as U
import Data.Word (Word8)
import Text.Printf (printf)

import Rota.Clock
import Rota.Sega
import Rota.Sega.Rom
import Rota.Snes (cgram15, snesTarget)
import Rota.Sound.Snes (brrSamples, dirBase, sampleBase, snesSoundBytes)

snesSpec :: RomSpec
snesSpec = RomSpec
  { rtPatternsFirst = True
  , rtTarget = snesTarget
  , rtSound = snesSoundBytes
  , rtBudget = snesBudget
  , rtCramOp = \_ _ -> (0, 0, 0)     -- (the Sega emitter's; not used here)
  , rtCramBytes = const []
  , rtSpritePos = \y x -> if x < 0 || x > 255 || y >= 224 then Nothing else Just (fromIntegral (y `mod` 256), fromIntegral x)
  , rtHeader = ""
  , rtNameNote = "" }

snesRom :: RomTarget
snesRom = romTarget snesSpec

-- | V-blank's master clocks: lines 225 to 261.
snesBudget :: Int
snesBudget = 37 * 1364

-- | A Sega colour RAM index (0-15 the background, 16 on the sprites) as
-- the SNES's CGRAM index.
cgOf :: Int -> Int
cgOf i = if i < 16 then i else 128 + (i - 16)

-- | A tile in the SNES's 4bpp format: per row, planes 0 and 1 (16 bytes),
-- then per row, planes 2 and 3 (bit 7 the leftmost pixel).
tileBytes4 :: Tile -> [Word8]
tileBytes4 t = concat [ [plane y 0, plane y 1] | y <- [0 .. 7] ] <> concat [ [plane y 2, plane y 3] | y <- [0 .. 7] ]
 where
  plane y pl = foldl (\acc x -> acc `shiftL` 1 .|. (if testBit (t U.! (y * 8 + x)) pl then 1 else 0)) 0 [0 .. 7 :: Int]

-- | What the screen shows at picture frame p (Rgb12, 4 bits a channel).
snesExpected :: Int -> U.Vector Rgb12
snesExpected = expected snesRom

-- | A ROM frame's cost in master clocks, as the player's loops take them
-- (a generous count: its fixed work, then per operation; a sound write
-- waits for the SPC700's echo).
frameCost' :: Int -> Int -> Int -> Int -> Int -> Int
frameCost' sound cram tiles sparks lights =
  4000 + 900 * sound + 150 * cram + 700 * tiles + 120 * (sparks + lights)

-- | Every ROM frame's cost, the intro and one period of each loop.
snesFrameCosts :: [Int]
snesFrameCosts =
  [ frameCost' (soundAt k) (len (cramRecs r) k) (len (tileRecs r) k) (len (sparkRecs r) k) (len (lightRecs r) k)
  | k <- [0 .. lead + idle + 120] ]
 where
  r = snesRom
  ck = tClock snesTarget
  lead = ckLead ck
  idle = ckIdle ck
  -- (frame 0's set-up runs while the display is dark: not counted)
  soundAt k = if k == 0 then 0 else (frameLens snesSoundBytes <> repeat 0) !! k
  len (Records i l) k = length (if k < length i then i !! k else l !! ((k - length i) `mod` length l))
  frameLens (0xFF : _) = []
  frameLens (n : rest) = fromIntegral n : frameLens (drop (2 * fromIntegral n) rest)
  frameLens [] = []

-- | The include file for the 65816 ROM.
snesRomInc :: String
snesRomInc = unlines $
  [ "; generated by rota-brand (Rota.Snes.Rom): the Super Nintendo demo's data"
  , printf ".DEFINE SPARK_SLOTS %d" (sparkSlots r)
  , printf ".DEFINE LIGHT_SLOTS %d" (lightSlots r)
  , printf ".DEFINE N_PATTERNS %d" (length (spritePatterns r))
  , ""
  , ".SECTION \"RotaData\" SUPERFREE"
  , "; BG1's tilemap, 32 x 28 entries (tile, priority 2000h on a logo cell)"
  , "TileMap:" ]
  <> [ ".DW " <> commaSep [ printf "$%04X" (ti .|. (if c == Logo then 0x2000 else 0)) | (c, ti) <- row ] | row <- chunks (tCols t) (zip (cells t) (cellTile r)) ]
  <> [ "TileMapEnd:", "", "; picture frame 0's tiles: VRAM word address, library graphic", "InitTiles:" ]
  <> [ printf ".DW %d" (M.size t0) ]
  <> concat [ [ printf ".DW $%04X" (16 * ti), printf ".DL SnesLib%d" (li M.! g) ] | (ti, g) <- M.toList t0 ]
  <> [ "", "; the sprites' colours, CGRAM 129 on", "SpriteCgram:" ]
  <> [ ".DW " <> commaSep [ printf "$%04X" (cgram15 (fromIntegral c)) | c <- spriteColours t ] ]
  <> [ "SpriteCgramEnd:", "", "; the sprite patterns (tiles 0 on)", "Patterns:" ]
  <> [ ".DB " <> commaSep (map hex2 (tileBytes4 p)) | p <- spritePatterns r ]
  <> [ "PatternsEnd:", ".ENDS", "", "; the tile library" ]
  <> concat [ [ printf ".SECTION \"SnesLib%d\" SUPERFREE" i, printf "SnesLib%d:" i, ".DB " <> commaSep (map hex2 (tileBytes4 g)), ".ENDS" ] | (i, g) <- zip [0 :: Int ..] (library r) ]
  <> stream "SnesTiles" (tileRecs r) (\(ti, g) -> [printf ".DW $%04X" (16 * ti), printf ".DL SnesLib%d" g])
  <> stream "SnesCgram" (cramRecs r) (\o -> case o of
        Cram i c -> [printf ".DB $%02X" (cgOf i), printf ".DW $%04X" (cgram15 (fromIntegral c))]
        Reg _ _ -> [".DB $FF", ".DW $000F"])
  <> stream "SnesSparks" (sparkRecs r) oamLine
  <> stream "SnesLights" (lightRecs r) oamLine
  <> [ "", ".SECTION \"SnesSound\" SUPERFREE", "SnesSound:" ]
  <> [ ".DB " <> commaSep (map hex2 c) | c <- chunks 32 snesSoundBytes ]
  <> [ ".ENDS" ]
 where
  r = snesRom
  t = snesTarget
  t0 = bgTiles r 0
  li = libIndex r
  oamLine (s, y, x, n) = [printf ".DB %d, $%02X, $%02X, $%02X" s x y n]
  stream :: String -> Records a -> (a -> [String]) -> [String]
  stream name (Records intro loop) line =
    [ "", printf ".SECTION \"%s\" SUPERFREE" name, name <> ":" ] <> concatMap (rec line) intro
    <> [ name <> "Loop:" ] <> concatMap (rec line) loop
    <> [ ".DB $FE", ".DL " <> name <> "Loop", ".ENDS" ]
  rec line ops
    | length ops >= 0xFE = error "snesRomInc: too many operations in a frame"
    | otherwise = printf ".DB %d" (length ops) : concatMap line ops

-- | The include file for the SPC700 program: the sample directory, then
-- the samples (BRR) from 'sampleBase', one block of bytes for the driver to
-- place at 'dirBase' (demos/snes/rota-spc.s).
snesSpcInc :: String
snesSpcInc = unlines $
  [ "; generated by rota-brand (Rota.Sound.Snes): the samples and their directory"
  , printf "; placed at $%04X (the directory), the samples from $%04X" dirBase sampleBase
  , "Dir:" ]
  <> [ printf ".DW $%04X, $%04X" a l | (a, l) <- snd brrSamples ]
  <> [ printf ".DSB %d $00" pad | pad > 0 ] <> [ "Samples:" ]
  <> [ ".DB " <> commaSep (map hex2 c) | c <- chunks 9 (fst brrSamples) ]
 where
  pad = sampleBase - dirBase - 4 * length (snd brrSamples)

-- | The figures (rota-stats).
snesStats :: String
snesStats = unlines
  [ printf "background tiles %d, library %d, sprite patterns %d" (1 + length (fabricSlots t) + length [ () | Logo <- cells t ]) (length (library r)) (length (spritePatterns r))
  , printf "sprite slots: sparks %d, lights %d" (sparkSlots r) (lightSlots r)
  , printf "sound bytes %d, samples %d bytes" (length snesSoundBytes) (length (fst brrSamples))
  , printf "frame cost: most %d of %d master clocks" (maximum snesFrameCosts) snesBudget ]
 where
  r = snesRom
  t = snesTarget

hex2 :: Word8 -> String
hex2 = printf "$%02X"

commaSep :: [String] -> String
commaSep [] = ""
commaSep xs = foldr1 (\a b -> a <> ", " <> b) xs

chunks :: Int -> [a] -> [[a]]
chunks _ [] = []
chunks n xs = take n xs : chunks n (drop n xs)
