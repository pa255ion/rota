{-|
The Game Gear demo's data (PLAN.md, side track J, step 5): "Rota.Gg"'s
pictures as the streams the ROM plays (@demos/gg/rota.s@, WLA-DX), by
"Rota.Sega.Rom" (its VRAM layout, frames and streams). The Game Gear's
own: the 160 × 144 window (sprites at (x + 48, y + 23), off the window
hidden), colour RAM words (two bytes an entry), and the time from the
frame interrupt (line 193) to the window's first line (24).
-}
module Rota.Gg.Rom
  ( ggRom
    -- * Tiles
  , bgTiles
  , cellTile
  , spritePatterns
    -- * Frames
  , TileOp
  , CramOp (..)
  , SatOp
  , frameCost
  , budget
  , romFrameCosts
    -- * Model
  , ggExpected
    -- * Output
  , ggRomInc
  , ggStats
  ) where

import Data.Bits (shiftR, (.&.))
import qualified Data.Map.Strict as M
import qualified Data.Vector.Unboxed as U

import Rota.Gg
import Rota.Sega.Rom (CramOp (..), RomSpec (..), RomTarget, SatOp, TileOp, frameCost)
import qualified Rota.Sega.Rom as R
import Rota.Sound.Gg (ggSoundBytes)

ggRom :: RomTarget
ggRom = R.romTarget RomSpec
  { rtPatternsFirst = False
  , rtTarget = ggTarget
  , rtSound = ggSoundBytes
  , rtBudget = budget
  , rtCramOp = \i c -> (fromIntegral (2 * i), fromIntegral (c .&. 0xFF), fromIntegral (c `shiftR` 8))
  , rtCramBytes = \c -> [fromIntegral (c .&. 0xFF), fromIntegral (c `shiftR` 8)]
  , rtSpritePos = \y x -> if x <= -8 || x >= ggW || y <= -8 || y >= ggH then Nothing else Just (fromIntegral (y + 23), fromIntegral (x + 48))
  , rtHeader = "; Generated by demos/rota-brand (Rota.Gg.Rom): the Game Gear demo's data."
  , rtNameNote = "; the window's name table: 18 rows of 20 entries (tile, high byte)"
  }

-- | T-states from the frame interrupt (line 193) to line 24.
budget :: Int
budget = (262 - 193 + 24) * 228

cellTile :: [Int]
cellTile = R.cellTile ggRom

bgTiles :: Int -> M.Map Int Tile
bgTiles = R.bgTiles ggRom

spritePatterns :: [Tile]
spritePatterns = R.spritePatterns ggRom

romFrameCosts :: [Int]
romFrameCosts = R.romFrameCosts ggRom

-- | What the window shows at picture frame p (before 0: the lead-in).
ggExpected :: Int -> U.Vector Rgb12
ggExpected = R.expected ggRom

ggRomInc :: String
ggRomInc = R.romInc ggRom

ggStats :: String
ggStats = R.romStats ggRom
