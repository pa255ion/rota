-- | Helpers for the generator's output files (Rota.Emit).
module Rota.Emit.Util
  ( header
  , hex2
  , chunks
  , rgbdsBytes
  , ca65Bytes
  ) where

import Data.List (intercalate)
import Data.Word (Word8)
import Numeric (showHex)

header :: String -> [String] -> String
header c ls = unlines (map ((c <> " ") <>) ("Generated by demos/rota-brand (Rota.Emit). Do not edit." : ls))

hex2 :: Word8 -> String
hex2 b = "$" <> pad (showHex b "")
 where
  pad x = replicate (2 - length x) '0' <> x

chunks :: Int -> [a] -> [[a]]
chunks _ [] = []
chunks k xs = take k xs : chunks k (drop k xs)

-- | @db@ lines, 16 bytes each.
rgbdsBytes :: [Word8] -> String
rgbdsBytes bs = unlines [ "    db " <> intercalate ", " (map hex2 c) | c <- chunks 16 bs ]

-- | @.byte@ lines, 16 bytes each.
ca65Bytes :: [Word8] -> String
ca65Bytes bs = unlines [ "    .byte " <> intercalate ", " (map hex2 c) | c <- chunks 16 bs ]

