{-|
The Master System demo's data (M6): "Rota.Sms"'s pictures as the streams
the ROM plays (@demos/sms/rota.s@, WLA-DX), by "Rota.Sega.Rom". The Master
System's own: the whole 256 × 192 screen (a sprite's Y is its top line
minus one, wrapping at the top; X its left column), colour RAM bytes (one
an entry: a record's third byte unused), and the time from the frame
interrupt (line 193) to the next frame's first line.
-}
module Rota.Sms.Rom
  ( smsRom
  , smsBudget
  , smsFrameCosts
  , smsExpected
  , smsRomInc
  , smsStats
  ) where

import qualified Data.Vector.Unboxed as U

import Rota.Sega (Rgb12)
import Rota.Sega.Rom (RomSpec (..), RomTarget)
import qualified Rota.Sega.Rom as R
import Rota.Sms
import Rota.Sound.Gg (ggSoundBytes)

smsRom :: RomTarget
smsRom = R.romTarget RomSpec
  { rtPatternsFirst = True
  , rtTarget = smsTarget
  , rtSound = ggSoundBytes
  , rtBudget = smsBudget
  , rtCramOp = \i c -> (fromIntegral i, cram6 c, 0)
  , rtCramBytes = \c -> [cram6 c]
  , rtSpritePos = pos
  , rtHeader = "; Generated by demos/rota-brand (Rota.Sms.Rom): the Master System demo's data."
  , rtNameNote = "; the screen's name table: 24 rows of 32 entries (tile, high byte)"
  }
 where
  -- no column left of 0 on this VDP (without its early clock): a sprite
  -- the model puts partly there would show wrong, so none may
  pos y x
    | y <= -8 || y >= smsH || x <= -8 || x >= smsW = Nothing
    | x < 0 = error ("smsRom: a sprite at x " <> show x)
    | otherwise = Just (fromIntegral ((y - 1) `mod` 256), fromIntegral x)

-- | T-states from the frame interrupt (line 193) to the next frame's line 0.
smsBudget :: Int
smsBudget = (262 - 193) * 228

smsFrameCosts :: [Int]
smsFrameCosts = R.romFrameCosts smsRom

-- | What the screen shows at picture frame p (before 0: the lead-in).
smsExpected :: Int -> U.Vector Rgb12
smsExpected = R.expected smsRom

smsRomInc :: String
smsRomInc = R.romInc smsRom

smsStats :: String
smsStats = R.romStats smsRom
