#!/bin/sh
# Generate platform/ps/input_codes.zig: the names of the Linux input
# event codes (KEY_*, BTN_*, ABS_*) that key-map files use, taken from the
# kernel header that ships with the pinned Zig (so the list follows the
# flake, not the host's kernel headers).
#
#   tools/gen-input-codes.sh [HEADER] > platform/ps/input_codes.zig
#
# For every code the name defined last with a number is the one written
# back (BTN_SOUTH, not BTN_GAMEPAD; BTN_0, not BTN_MISC); every other name
# (BTN_A, KEY_SCREENLOCK, ...) is still accepted when reading. *_MAX, *_CNT,
# KEY_RESERVED, ABS_RESERVED and KEY_MIN_INTERESTING are left out.
set -eu
header=${1:-$(dirname "$(command -v zig)")/../lib/zig/libc/include/any-linux-any/linux/input-event-codes.h}
test -f "$header" || { echo "gen-input-codes: no $header" >&2; exit 1; }

awk -v src="$(basename "$header")" '
/^#define (KEY|BTN|ABS)_[A-Za-z0-9_]+[ \t]/ {
    name = $2; val = $3
    if (name ~ /_(MAX|CNT)$/ || name == "KEY_RESERVED" || name == "ABS_RESERVED" || name == "KEY_MIN_INTERESTING") next
    if (val ~ /^0x[0-9a-fA-F]+$/) v = strtonum(val)
    else if (val ~ /^[0-9]+$/) v = val + 0
    else if (val in num) v = num[val]
    else next
    isabs = name ~ /^ABS_/
    num[name] = v
    order[++n] = name
    kind[name] = isabs
    if (val ~ /^(0x)?[0-9a-fA-F]+$/) canon[isabs, v] = name
}
END {
    print "//! Linux input event code names (KEY_*, BTN_*, ABS_*), generated by"
    print "//! tools/gen-input-codes.sh from the kernel header " src " that ships"
    print "//! with the pinned Zig. Do not edit; rerun the script."
    print ""
    print "pub const Name = struct { name: []const u8, code: u16, canonical: bool };"
    print ""
    print "/// KEY_* and BTN_* (one code space, 0 to 0x2FF)."
    print "pub const keys = [_]Name{"
    for (i = 1; i <= n; i++) { m = order[i]; if (!kind[m]) printf "    .{ .name = \"%s\", .code = 0x%03x, .canonical = %s },\n", m, num[m], (canon[0, num[m]] == m ? "true" : "false") }
    print "};"
    print ""
    print "/// ABS_* axes (0 to 0x3F)."
    print "pub const axes = [_]Name{"
    for (i = 1; i <= n; i++) { m = order[i]; if (kind[m]) printf "    .{ .name = \"%s\", .code = 0x%02x, .canonical = %s },\n", m, num[m], (canon[1, num[m]] == m ? "true" : "false") }
    print "};"
}' "$header"
